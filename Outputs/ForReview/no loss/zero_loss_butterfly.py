        center_call_pos = self.get_position(center_call_asset)
        upper_call_pos = self.get_position(upper_call_asset)

        # Verify quantities
        has_put = put_pos and put_pos.quantity >= 1
        has_center_calls = center_call_pos and center_call_pos.quantity <= -2  # Negative = short
        has_upper_call = upper_call_pos and upper_call_pos.quantity >= 1

        if not has_put:
            print(f"  Missing PUT (have: {put_pos.quantity if put_pos else 0}, need: 1)")
